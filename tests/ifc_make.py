Vec = tuple[float, float]
Ring = tuple[tuple[float, float, float], ...]
"""A planar face: points (x, y, z), counter-clockwise seen from above for a face that looks up."""
Tread = tuple[float, tuple[Vec, ...]]
"""One step of a stair: the height of its top (the file's z) and its outline."""
NS = uuid.UUID("5d3c9d0c-6a0b-4f5e-9a61-0c3f5c2f7a10")

OUTER = (("Aussenputz", 0.02), ("Mauerwerk", 0.30), ("Innenputz", 0.015))
"""Outside to inside: total 0.335 m, the core 0.30 m with 0.02 m outside and 0.015 m inside."""
INNER = (("Gipsputz", 0.01), ("Kalksandstein", 0.115), ("Gipsputz", 0.01))
FLOOR = (("Fliese", 0.02), ("Estrich", 0.13), ("Stahlbeton", 0.20))
"""A floor slab, top to bottom: finish 0.15 m on a 0.20 m core."""
DACH = (("Ziegel", 0.05), ("Sparren", 0.15))
"""A roof, top to bottom: tiles 0.05 m on rafters 0.15 m, 0.20 m square to the slope."""


@dataclass
class WallSpec:
    name: str
    p0: Vec
    p1: Vec
    """The ends of the line through the centre of the core."""
    storey: str = "EG"
    layers: tuple[tuple[str, float], ...] = OUTER
    first: Vec | None = None
    """World direction from the core centre to the first layer; none: no layer set usage, and the
    body is centred on the line."""
    z0: float = -0.15
    z1: float = 2.55
    type_name: str | None = None
    lb: bool = False
    status: str | None = None
    reverse: bool = False
    """The wall's own x axis runs from p1 to p0."""
    body: float | None = None
    """Thickness of the body where it differs from the layers' total (centred on the line)."""
    top: tuple[tuple[float, float], ...] | None = None
    """The top as a polyline: (distance along the wall from p0, height) pairs from the first end
    to the last. The body is then a mesh; `z1` is ignored."""


@dataclass
class OpeningSpec:
    name: str
    wall: str
    s0: float
    """Along the wall from p0 (not from the start of the body)."""
    width: float
    sill: float
    """From the FFL of the storey."""
    height: float
    kind: str = "win"
    type_name: str | None = None
    u: float | None = None


@dataclass
class SlabSpec:
    name: str
    storey: str
    z1: float
    """Top of the finish."""
    outline: tuple[Vec, ...]
    layers: tuple[tuple[str, float], ...] = FLOOR
    sense: str = "NEGATIVE"
    """Direction sense of the layer set usage: POSITIVE puts the first layer at the bottom."""
    type_name: str | None = "Decke 35"
    holes: tuple[tuple[Vec, ...], ...] = ()
    """Openings cut into the body of the slab itself (inner boundaries of its profile)."""


@dataclass
class SpaceSpec:
    name: str
    storey: str
    outline: tuple[Vec, ...]
    long_name: str | None = None
    z0: float = 0.0
    height: float = 2.5
    parent: bool = True
    """Aggregated under its storey, as most programs do; otherwise it hangs in the air and only its
    height says where it is."""


@dataclass
class GridSpec:
    tag: str
    p0: Vec
    p1: Vec
    """Two points on the axis, in the coordinates of the grid (see `House.grid_at`)."""
    v: bool = False
    """A V axis; otherwise a U axis."""


@dataclass
class VoidSpec:
    """An opening element cut into a floor slab."""

    name: str
    slab: str
    """Name of the floor slab."""
    outline: tuple[Vec, ...]


@dataclass
class StairSpec:
    name: str
    storey: str
    flights: tuple[tuple[Tread, ...], ...]
    landings: tuple[Tread, ...] = ()
    parts: bool = True
    """One IfcStair that aggregates an IfcStairFlight per flight and an IfcSlab per landing;
    otherwise one IfcStair with all the steps in its own body."""
    root: bool = True
    """Without the IfcStair: every flight is a product of its own (the landings are left out)."""
    base: float = 0.0
    """The steps are solid blocks from this height up to their tops."""
    status: str | None = None


@dataclass
class RoofSpec:
    name: str
    storey: str
    top: tuple[Ring, ...]
    """The planes of the top of the roof."""
    drop: float | None = 0.2
    """How far the underside lies below the top, vertically; none: a surface without thickness."""
    layers: tuple[tuple[str, float], ...] | None = DACH
    """Top to bottom; none: no material at all."""
    type_name: str | None = "Dach 20"
    parts: bool = True
    """One IfcRoof that aggregates a roof slab per plane; otherwise the body is the IfcRoof's."""
    root: bool = True
    """Without the IfcRoof: every plane is a roof slab of its own, with the layers."""


@dataclass
class RecessSpec:
    """A niche in a wall: an opening element nothing fills."""

    name: str
    wall: str
    s0: float
    width: float
    sill: float
    height: float


@dataclass
class House:
    storeys: dict[str, float] = field(default_factory=lambda: {"EG": 0.0, "OG": 2.9})
    walls: list[WallSpec] = field(default_factory=list[WallSpec])
    openings: list[OpeningSpec] = field(default_factory=list[OpeningSpec])
    slabs: list[SlabSpec] = field(default_factory=list[SlabSpec])
    spaces: list[SpaceSpec] = field(default_factory=list[SpaceSpec])
    extras: list[str] = field(default_factory=list[str])
    """Classes of things UEA does not map (IfcRoof, IfcColumn, ...), one product each, unnamed."""
    grids: list[GridSpec] = field(default_factory=list[GridSpec])
    grid_at: Vec = (0.0, 0.0)
    """Where the origin of the grid lies in the world."""
    grid_x: Vec = (1.0, 0.0)
    """Where the x axis of the grid points in the world."""
    voids: list[VoidSpec] = field(default_factory=list[VoidSpec])
    stairs: list[StairSpec] = field(default_factory=list[StairSpec])
    roofs: list[RoofSpec] = field(default_factory=list[RoofSpec])
    recesses: list[RecessSpec] = field(default_factory=list[RecessSpec])
    app: str = "Test-CAD 1.0"
    schema: Literal["IFC2X3", "IFC4", "IFC4X3"] = "IFC4"

    def wall(self, name: str) -> WallSpec:
        return next(w for w in self.walls if w.name == name)

    def without(self, *names: str) -> "House":
        """A copy without these elements (a wall takes its openings with it, a floor slab its
        openings)."""
        gone = set(names)
        return replace(
            self,
            walls=[w for w in self.walls if w.name not in gone],
            openings=[o for o in self.openings if o.name not in gone and o.wall not in gone],
            slabs=[x for x in self.slabs if x.name not in gone],
            spaces=[x for x in self.spaces if x.name not in gone],
            grids=[g for g in self.grids if g.tag not in gone],
            voids=[v for v in self.voids if v.name not in gone and v.slab not in gone],
            stairs=[x for x in self.stairs if x.name not in gone],
            roofs=[x for x in self.roofs if x.name not in gone],
            recesses=[r for r in self.recesses if r.name not in gone and r.wall not in gone],
        )

    def raised(self, dz: float) -> "House":
        """The same house with every height in the file `dz` higher."""

        def up(t: Tread) -> Tread:
            return (t[0] + dz, t[1])

        return replace(
            self,
            storeys={k: v + dz for k, v in self.storeys.items()},
            walls=[
                replace(
                    w,
                    z0=w.z0 + dz,
                    z1=w.z1 + dz,
                    top=None if w.top is None else tuple((s, z + dz) for s, z in w.top),
                )
                for w in self.walls
            ],
            slabs=[replace(x, z1=x.z1 + dz) for x in self.slabs],
            spaces=[replace(x, z0=x.z0 + dz) for x in self.spaces],
            stairs=[
                replace(
                    x,
                    flights=tuple(tuple(up(t) for t in f) for f in x.flights),
                    landings=tuple(up(t) for t in x.landings),
                    base=x.base + dz,
                )
                for x in self.stairs
            ],
            roofs=[
                replace(x, top=tuple(tuple((a, b, c + dz) for a, b, c in r) for r in x.top))
                for x in self.roofs
            ],
        )


def unit(a: Vec, b: Vec) -> Vec:
    d = math.hypot(b[0] - a[0], b[1] - a[1])
    return ((b[0] - a[0]) / d, (b[1] - a[1]) / d)


