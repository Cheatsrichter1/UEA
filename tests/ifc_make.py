"""Hand-built IFC files for the import tests.

A small house the way another program might write it: layer sets with usage on the walls (the
first layer on a side the file says), openings that void their wall, floor slabs with their finish
layers, spaces under their storey. Every number is chosen so the expected result can be worked out
by hand; the geometry is written explicitly (extruded rectangles, meshes for what has a slope),
nothing is generated by UEA. Stairs, roofs, grids and openings in the floor are added to a house
with the helpers at the end of the specs.
"""
