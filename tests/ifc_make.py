class Writer:
    def __init__(self, h: House) -> None:
        self.h = h
        self.f = ifcopenshell.file(schema=h.schema)
        if h.schema == "IFC2X3":
            # the old schema wants an owner history on everything
            org = self.f.create_entity("IfcOrganization", Name="Test")
            person = self.f.create_entity("IfcPerson", Id="t", FamilyName="Test")
            user = self.f.create_entity("IfcPersonAndOrganization", person, org)
            app = self.f.create_entity("IfcApplication", org, "1.0", "Test-CAD", "TC")
            ifcopenshell.api.owner.settings.get_user = lambda _: user
            ifcopenshell.api.owner.settings.get_application = lambda _: app
        self.guids: dict[str, str] = {}
        self.materials: dict[str, Any] = {}
        self.types: dict[str, Any] = {}
        self.slabs: dict[str, Any] = {}
        self.walls: dict[str, Any] = {}

    def guid(self, key: str) -> str:
        return ifcopenshell.guid.compress(uuid.uuid5(NS, key).hex)

    def entity(
        self, cls: str, key: str, name: str | None = None, predefined: str | None = None
    ) -> Any:
        e = ifcopenshell.api.root.create_entity(
            self.f, ifc_class=cls, predefined_type=predefined, name=name
        )
        e.GlobalId = self.guid(key)
        if name is not None and cls not in ("IfcProject", "IfcSite", "IfcBuilding"):
            self.guids[name] = e.GlobalId
        return e

    def pt(self, *c: float) -> Any:
        return self.f.createIfcCartesianPoint([float(x) for x in c])

    def axis(self, origin: tuple[float, ...], x: Vec | None = None) -> Any:
        ref = self.f.createIfcDirection([float(x[0]), float(x[1]), 0.0]) if x else None
        return self.f.createIfcAxis2Placement3D(self.pt(*origin), None, ref)

    def placed(self, parent: Any, origin: tuple[float, ...], x: Vec | None = None) -> Any:
        return self.f.createIfcLocalPlacement(parent, self.axis(origin, x))

    def body(self, *solids: Any, kind: str = "SweptSolid") -> Any:
        rep = self.f.createIfcShapeRepresentation(self.ctx, "Body", kind, list(solids))
        return self.f.createIfcProductDefinitionShape(None, None, [rep])

    def curve(self, outline: tuple[Vec, ...]) -> Any:
        pts = [self.f.createIfcCartesianPoint([float(x), float(y)]) for x, y in outline]
        return self.f.createIfcPolyline([*pts, pts[0]])

    def prism(
        self,
        outline: tuple[Vec, ...],
        z0: float,
        height: float,
        holes: tuple[tuple[Vec, ...], ...] = (),
    ) -> Any:
        if holes:
            profile = self.f.createIfcArbitraryProfileDefWithVoids(
                "AREA", None, self.curve(outline), [self.curve(h) for h in holes]
            )
        else:
            profile = self.f.createIfcArbitraryClosedProfileDef("AREA", None, self.curve(outline))
        return self.f.createIfcExtrudedAreaSolid(
            profile,
            self.axis((0.0, 0.0, z0)),
            self.f.createIfcDirection([0.0, 0.0, 1.0]),
            float(height),
        )

    def brep(self, faces: list[Ring]) -> Any:
        """A faceted solid from planar faces."""
        out = [
            self.f.createIfcFace(
                [
                    self.f.createIfcFaceOuterBound(
                        self.f.createIfcPolyLoop([self.pt(*q) for q in r]), True
                    )
                ]
            )
            for r in faces
        ]
        return self.f.createIfcFacetedBrep(self.f.createIfcClosedShell(out))

    def material(self, name: str) -> Any:
        if name not in self.materials:
            self.materials[name] = ifcopenshell.api.material.add_material(self.f, name=name)
        return self.materials[name]

    def layer_set(self, name: str, layers: tuple[tuple[str, float], ...]) -> Any:
        ls = ifcopenshell.api.material.add_material_set(
            self.f, name=name, set_type="IfcMaterialLayerSet"
        )
        for material, t in layers:
            layer = ifcopenshell.api.material.add_layer(
                self.f, layer_set=ls, material=self.material(material)
            )
            attributes: dict[str, Any] = {"LayerThickness": float(t)}
            if self.h.schema != "IFC2X3":
                attributes["Name"] = material  # the old schema has no name on a layer
            ifcopenshell.api.material.edit_layer(self.f, layer=layer, attributes=attributes)
        return ls

    def usage(self, product: Any, ls: Any, direction: str, sense: str, offset: float) -> None:
        use = self.f.createIfcMaterialLayerSetUsage(ls, direction, sense, float(offset))
        self.f.createIfcRelAssociatesMaterial(
            self.guid(f"mat/{product.GlobalId}"), None, None, None, [product], use
        )

    def type_of(self, cls: str, name: str) -> Any:
        if self.h.schema == "IFC2X3":
            cls = {"IfcDoorType": "IfcDoorStyle", "IfcWindowType": "IfcWindowStyle"}.get(cls, cls)
        if name not in self.types:
            self.types[name] = self.entity(cls, f"type/{name}", name)
        return self.types[name]

    def pset(self, product: Any, name: str, props: dict[str, Any]) -> None:
        ps = ifcopenshell.api.pset.add_pset(self.f, product=product, name=name)
        ifcopenshell.api.pset.edit_pset(self.f, pset=ps, properties=props)

    # --- the file

    def write(self, path: Path) -> dict[str, str]:
        f, h = self.f, self.h
        project = self.entity("IfcProject", "project", "Testhaus")
        project.UnitsInContext = f.createIfcUnitAssignment(
            [f.createIfcSIUnit(None, "LENGTHUNIT", None, "METRE")]
        )
        model_ctx = ifcopenshell.api.context.add_context(f, context_type="Model")
        self.ctx = ifcopenshell.api.context.add_context(
            f,
            context_type="Model",
            context_identifier="Body",
            target_view="MODEL_VIEW",
            parent=model_ctx,
        )
        site = self.entity("IfcSite", "site", "Site")
        building = self.building = self.entity("IfcBuilding", "building", "Haus")
        ifcopenshell.api.aggregate.assign_object(f, products=[site], relating_object=project)
        ifcopenshell.api.aggregate.assign_object(f, products=[building], relating_object=site)
        site.ObjectPlacement = self.placed(None, (0.0, 0.0, 0.0))
        building.ObjectPlacement = self.placed(site.ObjectPlacement, (0.0, 0.0, 0.0))
        self.storeys: dict[str, Any] = {}
        for name, z in h.storeys.items():
            st = self.entity("IfcBuildingStorey", f"storey/{name}", name)
            st.Elevation = float(z)
            st.ObjectPlacement = self.placed(building.ObjectPlacement, (0.0, 0.0, z))
            self.storeys[name] = st
        ifcopenshell.api.aggregate.assign_object(
            f, products=list(self.storeys.values()), relating_object=building
        )
        self.contained: dict[str, list[Any]] = {k: [] for k in self.storeys}
        for w in h.walls:
            self.walls[w.name] = self.wall(w)
        for o in h.openings:
            self.opening(o, h.wall(o.wall), self.walls[o.wall])
        for r in h.recesses:
            self.recess(r)
        for s in h.slabs:
            self.slab(s)
        for v in h.voids:
            self.void(v)
        for sp in h.spaces:
            self.space(sp)
        for st in h.stairs:
            self.stair(st)
        for rf in h.roofs:
            self.roof(rf)
        if h.grids:
            self.grid()
        for cls in h.extras:
            e = self.entity(cls, f"extra/{cls}")
            e.ObjectPlacement = self.placed(self.storeys["EG"].ObjectPlacement, (0.0, 0.0, 0.0))
            self.contained["EG"].append(e)
        for name, items in self.contained.items():
            if items:
                ifcopenshell.api.spatial.assign_container(
                    f, products=items, relating_structure=self.storeys[name]
                )
        f.header.file_name.originating_system = h.app
        f.write(str(path))
        return self.guids

    def wall(self, w: WallSpec) -> Any:
        e = self.entity(
            "IfcWall", f"wall/{w.name}", w.name, "SOLIDWALL" if w.lb else "PARTITIONING"
        )
        st_z = self.h.storeys[w.storey]
        a, b = (w.p1, w.p0) if w.reverse else (w.p0, w.p1)
        u = unit(a, b)
        left = (-u[1], u[0])
        length = math.hypot(b[0] - a[0], b[1] - a[1])
        total = sum(t for _, t in w.layers)
        core = max(range(len(w.layers)), key=lambda i: w.layers[i][1])
        if w.first is None:
            width = w.body or total
            lo, hi = -width / 2, width / 2
            ls = self.layer_set(w.type_name or w.name, w.layers)
            ifcopenshell.api.material.assign_material(
                self.f, products=[e], type="IfcMaterialLayerSet", material=ls
            )
        else:
            before = sum(t for _, t in w.layers[:core]) + w.layers[core][1] / 2
            towards_left = w.first[0] * left[0] + w.first[1] * left[1] > 0
            if towards_left:
                lo, hi = before - total, before
                sense, offset = "NEGATIVE", before
            else:
                lo, hi = -before, total - before
                sense, offset = "POSITIVE", -before
            ls = self.layer_set(w.type_name or w.name, w.layers)
            self.usage(e, ls, "AXIS2", sense, offset)
        e.ObjectPlacement = self.placed(
            self.storeys[w.storey].ObjectPlacement, (a[0], a[1], w.z0 - st_z), u
        )
        if w.top is None:
            outline = ((0.0, lo), (length, lo), (length, hi), (0.0, hi))
            e.Representation = self.body(self.prism(outline, 0.0, w.z1 - w.z0))
        else:
            faces = wall_faces(w, length, lo, hi)
            e.Representation = self.body(self.brep(faces), kind="Brep")
        if w.type_name:
            ifcopenshell.api.type.assign_type(
                self.f,
                related_objects=[e],
                relating_type=self.type_of("IfcWallType", w.type_name),
                should_map_representations=False,
            )
        props: dict[str, Any] = {"LoadBearing": w.lb}
        if w.status:
            props["Status"] = w.status
        self.pset(e, "Pset_WallCommon", props)
        self.contained[w.storey].append(e)
        return e

    def opening(self, o: OpeningSpec, w: WallSpec, wall: Any) -> None:
        box = wall_box(w, o.s0, o.width)
        st = self.storeys[w.storey]
        op = self.entity("IfcOpeningElement", f"opening/{o.name}", None, "OPENING")
        op.ObjectPlacement = self.placed(st.ObjectPlacement, (0.0, 0.0, 0.0))
        op.Representation = self.body(self.prism(box, o.sill, o.height))
        ifcopenshell.api.feature.add_feature(self.f, feature=op, element=wall)
        cls = "IfcDoor" if o.kind == "door" else "IfcWindow"
        e = self.entity(cls, f"{o.kind}/{o.name}", o.name, "DOOR" if o.kind == "door" else "WINDOW")
        e.ObjectPlacement = self.placed(st.ObjectPlacement, (0.0, 0.0, 0.0))
        e.OverallWidth = float(o.width)
        e.OverallHeight = float(o.height)
        e.Representation = self.body(self.prism(box, o.sill, o.height))
        ifcopenshell.api.feature.add_filling(self.f, opening=op, element=e)
        if o.type_name:
            t = self.type_of("IfcDoorType" if o.kind == "door" else "IfcWindowType", o.type_name)
            ifcopenshell.api.type.assign_type(
                self.f, related_objects=[e], relating_type=t, should_map_representations=False
            )
        if o.u is not None:
            self.pset(
                e,
                "Pset_DoorCommon" if o.kind == "door" else "Pset_WindowCommon",
                {"ThermalTransmittance": o.u},
            )
        self.contained[w.storey].append(e)

    def recess(self, r: RecessSpec) -> None:
        w = self.h.wall(r.wall)
        op = self.entity("IfcOpeningElement", f"recess/{r.name}", r.name, "RECESS")
        op.ObjectPlacement = self.placed(self.storeys[w.storey].ObjectPlacement, (0.0, 0.0, 0.0))
        op.Representation = self.body(self.prism(wall_box(w, r.s0, r.width), r.sill, r.height))
        ifcopenshell.api.feature.add_feature(self.f, feature=op, element=self.walls[r.wall])

    def slab(self, s: SlabSpec) -> None:
        e = self.entity("IfcSlab", f"slab/{s.name}", s.name, "FLOOR")
        self.slabs[s.name] = e
        total = sum(t for _, t in s.layers)
        e.ObjectPlacement = self.placed(self.storeys[s.storey].ObjectPlacement, (0.0, 0.0, 0.0))
        e.Representation = self.body(
            self.prism(s.outline, s.z1 - total - self.h.storeys[s.storey], total, s.holes)
        )
        ordered = s.layers if s.sense == "NEGATIVE" else tuple(reversed(s.layers))
        ls = self.layer_set(s.type_name or s.name, ordered)
        self.usage(e, ls, "AXIS3", s.sense, 0.0)
        if s.type_name:
            ifcopenshell.api.type.assign_type(
                self.f,
                related_objects=[e],
                relating_type=self.type_of("IfcSlabType", s.type_name),
                should_map_representations=False,
            )
        self.contained[s.storey].append(e)

    def void(self, v: VoidSpec) -> None:
        sl = next(x for x in self.h.slabs if x.name == v.slab)
        total = sum(t for _, t in sl.layers)
        z0 = sl.z1 - total - self.h.storeys[sl.storey]
        op = self.entity("IfcOpeningElement", f"void/{v.name}", v.name, "OPENING")
        op.ObjectPlacement = self.placed(self.storeys[sl.storey].ObjectPlacement, (0.0, 0.0, 0.0))
        op.Representation = self.body(self.prism(v.outline, z0 - 0.1, total + 0.2))
        ifcopenshell.api.feature.add_feature(self.f, feature=op, element=self.slabs[v.slab])

    def stair(self, st: StairSpec) -> None:
        place = self.storeys[st.storey].ObjectPlacement
        z_st = self.h.storeys[st.storey]

        def blocks(treads: tuple[Tread, ...]) -> list[Any]:
            return [self.prism(o, st.base - z_st, top - st.base) for top, o in treads]

        if not st.root:
            for i, fl in enumerate(st.flights):
                name = st.name if len(st.flights) == 1 else f"{st.name} Lauf {i + 1}"
                e = self.entity("IfcStairFlight", f"stair/{st.name}/flight{i}", name)
                e.ObjectPlacement = self.placed(place, (0.0, 0.0, 0.0))
                e.Representation = self.body(*blocks(fl))
                if st.status:
                    self.pset(e, "Pset_StairFlightCommon", {"Status": st.status})
                self.contained[st.storey].append(e)
            return
        root = self.entity("IfcStair", f"stair/{st.name}", st.name)
        root.ObjectPlacement = self.placed(place, (0.0, 0.0, 0.0))
        if st.parts:
            parts: list[Any] = []
            for i, fl in enumerate(st.flights):
                e = self.entity(
                    "IfcStairFlight", f"stair/{st.name}/flight{i}", f"{st.name} Lauf {i + 1}"
                )
                e.ObjectPlacement = self.placed(root.ObjectPlacement, (0.0, 0.0, 0.0))
                e.Representation = self.body(*blocks(fl))
                parts.append(e)
            for i, landing in enumerate(st.landings):
                e = self.entity(
                    "IfcSlab", f"stair/{st.name}/landing{i}", f"{st.name} Podest {i + 1}", "LANDING"
                )
                e.ObjectPlacement = self.placed(root.ObjectPlacement, (0.0, 0.0, 0.0))
                e.Representation = self.body(*blocks((landing,)))
                parts.append(e)
            ifcopenshell.api.aggregate.assign_object(self.f, products=parts, relating_object=root)
        else:
            every = tuple(t for fl in st.flights for t in fl) + st.landings
            root.Representation = self.body(*blocks(every))
        if st.status:
            self.pset(root, "Pset_StairCommon", {"Status": st.status})
        self.contained[st.storey].append(root)

    def roof(self, r: RoofSpec) -> None:
        place = self.storeys[r.storey].ObjectPlacement
        z_st = self.h.storeys[r.storey]

        def low(face: Ring) -> Ring:
            return tuple((x, y, z - z_st) for x, y, z in face)

        if not r.root:
            for i, top in enumerate(r.top):
                name = r.name if len(r.top) == 1 else f"{r.name} {i + 1}"
                e = self.entity("IfcSlab", f"roof/{r.name}/{i}", name, "ROOF")
                e.ObjectPlacement = self.placed(place, (0.0, 0.0, 0.0))
                e.Representation = self.body(
                    self.brep([low(f) for f in thick(top, r.drop)]), kind="Brep"
                )
                if r.layers:
                    self.usage(
                        e, self.layer_set(r.type_name or r.name, r.layers), "AXIS3", "NEGATIVE", 0.0
                    )
                self.contained[r.storey].append(e)
            return
        root = self.entity("IfcRoof", f"roof/{r.name}", r.name)
        root.ObjectPlacement = self.placed(place, (0.0, 0.0, 0.0))
        if r.parts:
            pieces: list[Any] = []
            for i, top in enumerate(r.top):
                e = self.entity("IfcSlab", f"roof/{r.name}/{i}", f"{r.name} {i + 1}", "ROOF")
                e.ObjectPlacement = self.placed(root.ObjectPlacement, (0.0, 0.0, 0.0))
                e.Representation = self.body(
                    self.brep([low(f) for f in thick(top, r.drop)]), kind="Brep"
                )
                pieces.append(e)
            ifcopenshell.api.aggregate.assign_object(self.f, products=pieces, relating_object=root)
        else:
            faces = [low(f) for top in r.top for f in thick(top, r.drop)]
            root.Representation = self.body(self.brep(faces), kind="Brep")
        if r.layers:
            self.usage(
                root, self.layer_set(r.type_name or r.name, r.layers), "AXIS3", "NEGATIVE", 0.0
            )
        if r.type_name and self.h.schema != "IFC2X3":  # the old schema has no roof types
            ifcopenshell.api.type.assign_type(
                self.f,
                related_objects=[root],
                relating_type=self.type_of("IfcRoofType", r.type_name),
                should_map_representations=False,
            )
        self.contained[r.storey].append(root)

    def grid(self) -> None:
        h = self.h
        g = self.entity("IfcGrid", "grid", "Raster")
        at = (h.grid_at[0], h.grid_at[1], 0.0)
        g.ObjectPlacement = self.placed(self.building.ObjectPlacement, at, h.grid_x)

        def axis(a: GridSpec) -> Any:
            pts = [self.f.createIfcCartesianPoint([float(c) for c in q]) for q in (a.p0, a.p1)]
            return self.f.createIfcGridAxis(a.tag, self.f.createIfcPolyline(pts), True)

        g.UAxes = [axis(a) for a in h.grids if not a.v]
        g.VAxes = [axis(a) for a in h.grids if a.v]
        self.contained[next(iter(self.storeys))].append(g)

    def space(self, sp: SpaceSpec) -> None:
        e = self.entity("IfcSpace", f"space/{sp.name}", sp.name)
        e.LongName = sp.long_name
        e.ObjectPlacement = self.placed(self.storeys[sp.storey].ObjectPlacement, (0.0, 0.0, 0.0))
        e.Representation = self.body(
            self.prism(sp.outline, sp.z0 - self.h.storeys[sp.storey], sp.height)
        )
        if sp.parent:
            ifcopenshell.api.aggregate.assign_object(
                self.f, products=[e], relating_object=self.storeys[sp.storey]
            )


def write(h: House, path: Path) -> dict[str, str]:
    """Write the file; the result maps the name of each element to its GlobalId."""
    return Writer(h).write(path)
