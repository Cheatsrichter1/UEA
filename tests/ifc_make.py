# ---------- stairs and roofs worked out with plain arithmetic ----------


def rect(x0: float, y0: float, x1: float, y1: float) -> tuple[Vec, ...]:
    return ((x0, y0), (x1, y0), (x1, y1), (x0, y1))


CLIMB = {"n": (0.0, 1.0), "s": (0.0, -1.0), "e": (1.0, 0.0), "w": (-1.0, 0.0)}


def stair_steps(
    x0: float,
    y0: float,
    up: str,
    w: float,
    n: int,
    tread: float,
    rise: float,
    shape: str = "straight",
    turn: str = "l",
    n1: int | None = None,
    gap: float = 0.1,
    z0: float = 0.0,
) -> tuple[tuple[tuple[Tread, ...], ...], tuple[Tread, ...]]:
    """The flights and the landing of a stair: n risers of `rise` above z0, the first flight
    climbing `up`, the footprint starting at the corner (x0, y0). A straight stair has n-1 steps;
    an L or U stair has a landing as the step after the first flight, then the second flight.

    The steps are laid out in a frame with p along the first flight and q toward the turn, and
    carried into the plan by the direction of the climb.
    """
    cp = CLIMB[up]
    left = (-cp[1], cp[0])
    cq = left if turn == "l" else (-left[0], -left[1])

    def plan(p: float, q: float) -> Vec:
        return (cp[0] * p + cq[0] * q, cp[1] * p + cq[1] * q)

    boxes: list[tuple[int, tuple[float, float, float, float], bool]] = []
    """(number of the step, (p0, q0, p1, q1), landing?) per step, flight 1 first."""
    flights: list[list[int]] = [[]]
    if shape == "straight":
        for i in range(1, n):
            boxes.append((i, ((i - 1) * tread, 0.0, i * tread, w), False))
            flights[0].append(len(boxes) - 1)
    else:
        first = n1 if n1 is not None else n // 2
        a1 = (first - 1) * tread
        count2 = n - first - 1
        for i in range(1, first):
            boxes.append((i, ((i - 1) * tread, 0.0, i * tread, w), False))
            flights[0].append(len(boxes) - 1)
        if shape == "l":
            boxes.append((first, (a1, 0.0, a1 + w, w), True))
        else:
            boxes.append((first, (a1, 0.0, a1 + w, 2 * w + gap), True))
        flights.append([])
        for j in range(1, count2 + 1):
            if shape == "l":
                box = (a1, w + (j - 1) * tread, a1 + w, w + j * tread)
            else:
                box = (a1 - j * tread, w + gap, a1 - (j - 1) * tread, 2 * w + gap)
            boxes.append((first + j, box, False))
            flights[1].append(len(boxes) - 1)
    corners = [plan(p, q) for _, (p0, q0, p1, q1), _ in boxes for p, q in ((p0, q0), (p1, q1))]
    dx = x0 - min(c[0] for c in corners)
    dy = y0 - min(c[1] for c in corners)

    def step(k: int) -> Tread:
        number, (p0, q0, p1, q1), _ = boxes[k]
        a, b = plan(p0, q0), plan(p1, q1)
        return (
            z0 + number * rise,
            rect(
                min(a[0], b[0]) + dx,
                min(a[1], b[1]) + dy,
                max(a[0], b[0]) + dx,
                max(a[1], b[1]) + dy,
            ),
        )

    landings = tuple(step(k) for k, (_, _, land) in enumerate(boxes) if land)
    return tuple(tuple(step(k) for k in f) for f in flights), landings


def gable_x(
    x0: float, x1: float, y0: float, y1: float, z_edge: float, pitch: float
) -> tuple[Ring, Ring]:
    """The two planes of the top of a gable roof with its ridge along x in the middle of y0..y1,
    both eaves at height z_edge, pitch in degrees. South plane first."""
    t = math.tan(math.radians(pitch))
    ym = (y0 + y1) / 2
    zr = z_edge + t * (ym - y0)
    south = ((x0, y0, z_edge), (x1, y0, z_edge), (x1, ym, zr), (x0, ym, zr))
    north = ((x0, ym, zr), (x1, ym, zr), (x1, y1, z_edge), (x0, y1, z_edge))
    return south, north


def outward(points: Ring, toward: tuple[float, float, float]) -> Ring:
    """The face with its points ordered so that its normal points the way of `toward`."""
    nx = ny = nz = 0.0
    for i, a in enumerate(points):
        b = points[(i + 1) % len(points)]
        nx += (a[1] - b[1]) * (a[2] + b[2])
        ny += (a[2] - b[2]) * (a[0] + b[0])
        nz += (a[0] - b[0]) * (a[1] + b[1])
    if nx * toward[0] + ny * toward[1] + nz * toward[2] < 0:
        return tuple(reversed(points))
    return points


def thick(top: Ring, drop: float | None) -> list[Ring]:
    """The faces of a slab-like body: a face that looks up, the same face `drop` lower looking
    down, and the walls between. Without `drop` only the face."""
    faces = [outward(top, (0.0, 0.0, 1.0))]
    if drop is None:
        return faces
    faces.append(outward(tuple((x, y, z - drop) for x, y, z in top), (0.0, 0.0, -1.0)))
    for i, a in enumerate(top):
        b = top[(i + 1) % len(top)]
        dx, dy = b[0] - a[0], b[1] - a[1]
        wall = (
            (a[0], a[1], a[2]),
            (b[0], b[1], b[2]),
            (b[0], b[1], b[2] - drop),
            (a[0], a[1], a[2] - drop),
        )
        faces.append(outward(wall, (dy, -dx, 0.0)))
    return faces


def wall_box(w: WallSpec, s0: float, width: float) -> tuple[Vec, ...]:
    """The plan of an opening in a wall: `width` along it from `s0` (from p0), 0.5 m deep,
    centred on the line."""
    a = w.p0
    u = unit(w.p0, w.p1)
    left = (-u[1], u[0])
    lo, hi = s0, s0 + width
    return (
        (a[0] + u[0] * lo - left[0] * 0.25, a[1] + u[1] * lo - left[1] * 0.25),
        (a[0] + u[0] * hi - left[0] * 0.25, a[1] + u[1] * hi - left[1] * 0.25),
        (a[0] + u[0] * hi + left[0] * 0.25, a[1] + u[1] * hi + left[1] * 0.25),
        (a[0] + u[0] * lo + left[0] * 0.25, a[1] + u[1] * lo + left[1] * 0.25),
    )


def wall_faces(w: WallSpec, length: float, lo: float, hi: float) -> list[Ring]:
    """The faces of a wall whose top is a polyline, in the wall's own frame (x along the wall
    from its first end, y across, z above the foot of the wall)."""
    assert w.top is not None
    prof = sorted(((length - s if w.reverse else s), z - w.z0) for s, z in w.top)
    faces: list[Ring] = [
        outward(((0.0, lo, 0.0), (length, lo, 0.0), (length, hi, 0.0), (0.0, hi, 0.0)), (0, 0, -1))
    ]
    for (sa, za), (sb, zb) in pairwise(prof):
        faces.append(
            outward(((sa, lo, za), (sb, lo, zb), (sb, hi, zb), (sa, hi, za)), (0.0, 0.0, 1.0))
        )
    for v, toward in ((lo, (0.0, -1.0, 0.0)), (hi, (0.0, 1.0, 0.0))):
        side = ((0.0, v, 0.0), (length, v, 0.0), *((sx, v, zx) for sx, zx in reversed(prof)))
        faces.append(outward(side, toward))
    z_first, z_last = prof[0][1], prof[-1][1]
    faces.append(
        outward(
            ((0.0, lo, 0.0), (0.0, hi, 0.0), (0.0, hi, z_first), (0.0, lo, z_first)), (-1, 0, 0)
        )
    )
    faces.append(
        outward(
            ((length, lo, 0.0), (length, hi, 0.0), (length, hi, z_last), (length, lo, z_last)),
            (1, 0, 0),
        )
    )
    return faces


